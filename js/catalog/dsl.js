/**
 * Компактный конструктор записей каталога.
 * Позиционные аргументы выбраны осознанно: одна игра — одна строка, файл легко просматривать глазами,
 * а весь «длинный» текст (описания) остаётся единственным, что занимает место.
 *
 * g(название, год, студия, жанры, теги, режимы, [мин,макс] игроков, платформы,
 *   ценовая категория, примерная цена ₽, [основной сюжет, completionist-оценка], сложность, темп, рейтинг,
 *   настроения, {ru, en}, { coopQ, gp, psp, slug, cloud:false }).
 *   Для неизвестной сложности/темпа указывайте null; не подменяйте догадкой.
 */
export const g = (t, y, dev, gr, tg, md, pl, pf, pr, pv, len, dif, pace, rat, mood, desc, extra = {}) => ({
  t, y, dev, gr, tg, md, pl, pf, pr, pv, len, dif, pace, rat, mood, desc, ...extra,
});
