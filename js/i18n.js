let current = 'ru';

export const setLang = (lang) => { current = STRINGS[lang] ? lang : 'ru'; return current; };
export const getLang = () => current;

/** t('quiz.step', { n: 2, total: 8 }) → «Вопрос 2 из 8» */
export function t(key, vars = {}) {
  const dict = STRINGS[current] || STRINGS.ru;
  const raw = dict[key] ?? STRINGS.ru[key] ?? key;
  return Object.entries(vars).reduce((acc, [k, v]) => acc.replaceAll(`{${k}}`, String(v)), raw);
}

/** Локализованная подпись из словаря таксономии */
export const tl = (dict, id) => dict[id]?.[current] ?? id;

/** Русская плюрализация: one (1 игра), few (3 игры), many (5 игр); в en — one/other */
function pluralForm(n, lang) {
  if (lang !== 'ru') return n === 1 ? 'one' : 'other';
  const m10 = Math.abs(n) % 10, m100 = Math.abs(n) % 100;
  if (m10 === 1 && m100 !== 11) return 'one';
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return 'few';
  return 'many';
}

/**
 * Строка с числом: tp('catalog.found', 5) → «Найдено 5 игр».
 * В словаре должны быть ключи <base>.one/.few/.many (ru) и .one/.other (en).
 * Покрытие проверяет test-functional §11.
 */
export function tp(key, n, vars = {}) {
  return t(`${key}.${pluralForm(Number(n) || 0, current)}`, { n, ...vars });
}
