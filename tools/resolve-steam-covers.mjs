#!/usr/bin/env node
/** Resolve official Steam Store art for catalog games.
 * Run with network access: node tools/resolve-steam-covers.mjs [--limit N]
 * The output is reviewable source data, never a random image search result.
 */
import { writeFile, readFile } from 'node:fs/promises';
import { GAMES } from '../js/catalog/index.js';
const out = new URL('../js/catalog/steam-covers.js', import.meta.url);
const limit = Number(process.argv.find((x) => x.startsWith('--limit='))?.split('=')[1] || Infinity);
let existing = {};
try { existing = (await import(`${out.href}?cache=${Date.now()}`)).STEAM_COVERS || {}; } catch {}
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const result = { ...existing };
for (const game of GAMES.filter((g) => !result[g.slug]).slice(0, limit)) {
  const url = `https://store.steampowered.com/api/storesearch/?term=${encodeURIComponent(game.t)}&l=english&cc=us`;
  try {
    const res = await fetch(url, { headers: { 'User-Agent': 'GustoPlay catalog metadata resolver/1.0' } });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const data = await res.json();
    const exact = (data.items || []).find((x) => String(x.name).trim().toLowerCase() === game.t.trim().toLowerCase());
    if (exact?.id) result[game.slug] = { steamId: exact.id, cover: `https://cdn.akamai.steamstatic.com/steam/apps/${exact.id}/library_600x900_2x.jpg` };
    else console.warn(`No exact match: ${game.t}`);
  } catch (error) { console.warn(`Skipped ${game.t}: ${error.message}`); }
  await sleep(350);
}
const lines = Object.entries(result).sort().map(([slug, value]) => `  ${JSON.stringify(slug)}: ${JSON.stringify(value)},`);
await writeFile(out, `/** Generated by tools/resolve-steam-covers.mjs; review matches before publishing. */\nexport const STEAM_COVERS = {\n${lines.join('\n')}\n};\n`);
console.log(`Saved ${Object.keys(result).length}/${GAMES.length} reviewed Steam matches to ${out.pathname}`);
