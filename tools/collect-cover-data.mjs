#!/usr/bin/env node
/** Забирает результат резолвера обложек из аннотаций прогона GitHub Actions
 * и записывает его в js/catalog/steam-covers.js (см. .github/workflows/covers.yml
 * и tools/emit-cover-data.mjs).
 *
 *   node tools/collect-cover-data.mjs <run-id>
 *
 * Требует `gh` с доступом к api.github.com (в песочнице он есть).
 */
import { execFileSync } from 'node:child_process';
import { writeFile } from 'node:fs/promises';

const runId = process.argv[2];
if (!runId) {
  console.error('Использование: node tools/collect-cover-data.mjs <run-id>');
  process.exit(1);
}

const gh = (args) => execFileSync('gh', args, { encoding: 'utf8' });
const jobs = JSON.parse(gh(['run', 'view', runId, '--json', 'jobs', '-q', '.'])).jobs;
const job = jobs.find((j) => /Резолвинг|обложек|resolve/i.test(j.name)) || jobs[0];

const annotations = [];
for (let page = 1; ; page += 1) {
  const chunk = JSON.parse(gh(['api', `repos/nigerader-dev/Gustoplay/check-runs/${job.databaseId}/annotations?per_page=100&page=${page}`]));
  annotations.push(...chunk);
  if (chunk.length < 100) break;
}

const chunks = annotations
  .filter((a) => a.message.startsWith('covers-b64'))
  .map((a) => ({ idx: Number(a.message.match(/\[(\d+)\//)[1]), data: a.message.split(': ').slice(1).join(': ').trim() }))
  .sort((a, b) => a.idx - b.idx);

if (!chunks.length) {
  console.error('Аннотации covers-b64 не найдены — прогон ещё идёт или упал до шага доставки.');
  process.exit(1);
}
const meta = annotations.find((a) => a.message.startsWith('covers-meta'))?.message;
const map = JSON.parse(Buffer.from(chunks.map((c) => c.data).join(''), 'base64').toString('utf8'));
console.log(`${meta || `чанков: ${chunks.length}`}`);

const lines = Object.entries(map)
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  .map(([slug, value]) => `  ${JSON.stringify(slug)}: ${JSON.stringify(value)},`);
const file = `/** Generated by tools/resolve-steam-covers.mjs — review matches before publishing. Ручные правки: tools/steam-overrides.json. */\nexport const STEAM_COVERS = {\n${lines.join('\n')}\n};\n`;
await writeFile(new URL('../js/catalog/steam-covers.js', import.meta.url), file);
console.log(`Записано ${lines.length} обложек в js/catalog/steam-covers.js`);

const misses = annotations.filter((a) => a.message.startsWith('cover-review:')).map((a) => a.message.replace('cover-review: ', ''));
if (misses.length) {
  console.log('\nНерешённые (нужны оверрайды):');
  misses.forEach((m) => console.log(`  • ${m}`));
}
